  const чм = (s) => { const m = String(s || '').match(/(\d{1,2}):(\d{2})/); return m && Number(m[1]) < 24 && Number(m[2]) < 60 ? m[1].padStart(2, '0') + ':' + m[2] : ''; };
  const мин = (hm) => { const x = чм(hm); return x ? Number(x.slice(0, 2)) * 60 + Number(x.slice(3, 5)) : NaN; };
  const дмг = (iso) => (iso ? iso.slice(8, 10) + '.' + iso.slice(5, 7) + '.' + iso.slice(0, 4) : '');
  const дм = (iso) => (iso ? iso.slice(8, 10) + '.' + iso.slice(5, 7) : '');
  const днейМежду = (a, b) => (a && b ? Math.round((Date.parse(b) - Date.parse(a)) / 864e5) : NaN);
  // «сегодня» / «завтра» / «08.10» — для клиента и для чата
  const когда = (iso, c) => { const d = днейМежду(c && c.сейчас && c.сейчас.date, iso); return d === 0 ? 'сегодня' : d === 1 ? 'завтра' : дм(iso); };
  // сейчас + N минут (время города) — до минуты, как «Через час» в CRM; идут секунды (сек > 0) — вверх на минуту:
  // 14:05:40 + час = 15:06, а не 15:05 (иначе до визита 59 минут)
  function плюсМинут(сейчас, n) {
    if (!сейчас || !сейчас.date || !чм(сейчас.time)) return null;
    let m = мин(сейчас.time) + n + (сейчас.сек > 0 ? 1 : 0);
    const d = new Date(Date.parse(сейчас.date + 'T00:00:00Z') + Math.floor(m / 1440) * 864e5).toISOString().slice(0, 10);
    m %= 1440;
    return { date: d, time: String(Math.floor(m / 60)).padStart(2, '0') + ':' + String(m % 60).padStart(2, '0') };
  }
  // телефон — «+7 916-123-4567» (как «свяжитесь по сд»); в служебном бывает «звонить на второй номер» — тот главнее (СД)
  const ТЕЛ = /(?:\+?7|8)[\s(\-]*\d{3}[\s)\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}/;
  function телефон(c) {
    const из = (String((c && c.служебный) || '').match(ТЕЛ) || [])[0];
    const p = String(из || (c && c.тел) || '').replace(/\D/g, '').slice(-10);
    return p.length === 10 ? '+7 ' + p.slice(0, 3) + '-' + p.slice(3, 6) + '-' + p.slice(6) : '';
  }
  // в журнал и заметки телефоны не пишем целиком: «+7 9••-•••-••12». Ловим и номер без +7/8 («916 123 45 67» — оператор мог
  // так поправить текст); цифры по краям — не номер (№ заявки рядом, дата), иначе последняя цифра осталась бы видна
  const ТЕЛ_ВСЕ = /(?<![\d+])(?:(?:\+7|7|8)[\s(\-]*)?\(?[3-9]\d{2}[\s)\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)/g;
  const маскаТел = (s) => String(s || '').replace(ТЕЛ_ВСЕ, (x) => { const d = x.replace(/\D/g, '').slice(-10); return '+7 ' + d[0] + '••-•••-••' + d.slice(-2); });
  const кратко = (s) => String(s || '').replace(/\s+/g, ' ').trim().slice(0, Н.пороги.кратко);
  const ПОЛЕ_ИМЯ = { comment: 'Комментарий', service: 'Служебный', partner: 'Комментарий партнёра' };
  // строка превью про комментарий партнёра: ядро CRM пишет его, только если у заявки есть партнёр (как crm.cancelKc)
  const партнёру = (s, t) => (s.hasPartner === false ? '' : ', партнёру — «' + t + '»');
  const кнопкаЕсть = (s, nb) => (!nb ? true : (Array.isArray(nb) ? nb : [nb]).some((b) => !!(s.buttons && s.buttons[b])));
  // галочка CRM: true / 1 / '1' (select «Дальний выезд» — '0'/'1'); null — поля нет
  const вкл = (x) => x === true || x === 1 || x === '1' || x === 'on' || x === 'true';

  /* Снимок карточки (контракт 2.3) — в одном виде: код статуса по шапке, если кода нет; галочки — true/false (null — поля нет);
     принимает и ответ ядра целиком ({ok, card}) */
  function снимок(snap) {
    const s = { ...(snap && snap.card && typeof snap.card === 'object' ? snap.card : snap || {}) };
    s.statusCode = (СТАТУСЫ[Number(s.statusCode)] && Number(s.statusCode)) || кодСтатуса(s.statusName);
    s.id = String(s.id || '');
    s.buttons = s.buttons && typeof s.buttons === 'object' ? s.buttons : {};
    s.transferServers = Array.isArray(s.transferServers) ? s.transferServers.filter((x) => x && x.key) : [];
    s.flags = Object.fromEntries(Object.entries(s.flags || {}).map(([k, x]) => [k, x === null || x === undefined ? x : вкл(x)]));
    return s;
  }

  /* Ввод с экрана: имена полей экрана (actions-ui.js) → имена плана. Так одинаково работают и поля LC_ACT.поля, и запасные поля экрана */
  function вводИз(key, ввод) {
    const v = { ...(ввод || {}) };
    const есть = (x) => x !== undefined && x !== null && x !== '';
    if (key === 'precheck_close' && !есть(v.code) && /^\d{3}$/.test(String(v.reason || ''))) { v.code = Number(v.reason); delete v.reason; }
    if (есть(v.claimType)) v.typeNo = Number(v.claimType);                // выбор на экране главнее подсказки
    if (key === 'feedback' && !есть(v.type) && есть(v.fbType)) v.type = Number(v.fbType);
    if (v.городПроверен === undefined && v.cityOk !== undefined) v.городПроверен = вкл(v.cityOk);
    if (!есть(v.случай) && есть(v.case)) v.случай = v.case;
    if (typeof v.случай === 'string' && /^\d+$/.test(v.случай)) v.случай = Number(v.случай);
    if (key === 'repeat_ask') {
      if (!есть(v.вид) && есть(v.kind)) v.вид = /гарант/.test(String(v.kind)) ? 'гарантия' : 'повтор';
      if (v.другой === undefined && v.other !== undefined) v.другой = вкл(v.other);
    }
    if (key === 'comment' && v.field === 'comments') v.field = 'comment';
    if (key === 'flags' || key === 'edit') for (const g of ГАЛОЧКИ) if (есть(v[g[0]])) v[g[0]] = вкл(v[g[0]]);
    if (v.agreed !== undefined) v.agreed = вкл(v.agreed);
    return v;
  }

  /* Контекст экрана → контекст плана. Экран (actions-ui.js) даёт {cr (запись «created»), city, tz, now}; план ждёт
     сейчас {date,time} по городу, телефон для СД/«стыка», служебный, претензию, чат заявки. Явно переданное — главнее */
  function сейчасВГороде(now, tz, город) {
    const d = new Date(Number(now) || Date.now());
    try {
      if (typeof LC_EXTRACT !== 'undefined' && LC_EXTRACT.clientTz && LC_EXTRACT.localParts) {
        const p = LC_EXTRACT.localParts(d, LC_EXTRACT.clientTz(tz || '', город || '').tz);
        return { date: p.iso, time: p.hm, сек: d.getSeconds() };
      }
      const f = new Intl.DateTimeFormat('ru-RU', { timeZone: tz || 'Europe/Moscow', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false });
      const p = {};
      for (const x of f.formatToParts(d)) p[x.type] = x.value;
      return { date: p.year + '-' + p.month + '-' + p.day, time: (p.hour === '24' ? '00' : p.hour) + ':' + p.minute };
    } catch (_e) { return null; }
  }
  function контекст(ctx) {
    const c = { ...(ctx || {}) };
    const cr = c.cr && typeof c.cr === 'object' ? c.cr : c.created && typeof c.created === 'object' ? c.created : null;
    if (cr) {
      if (c.тел === undefined && cr.phone10) c.тел = cr.phone10;
      if (c.служебный === undefined && cr.service) c.служебный = cr.service;
      if (c.hasClaim === undefined && cr.hasClaim !== undefined) c.hasClaim = !!cr.hasClaim;
      if (c.claimMsg === undefined && cr.claimMsg) c.claimMsg = cr.claimMsg;
      if (c.чатЗаявки === undefined && cr.chat) c.чатЗаявки = String(cr.chat);
      if (!c.город && cr.city) c.город = cr.city;
    }
    if (!c.город && c.city) c.город = c.city;
    // территория адреса (как у создания): спутник — срочная за 2 ч и с 11:00; самая ранняя — по территории
    if (c.terr && typeof c.terr === 'object') {
      if (c.спутник === undefined && c.terr.satelliteOf) c.спутник = true;
      if (!c.ранняя && c.terr.earliest) c.ранняя = c.terr.earliest;
    }
    if (!c.сейчас && (c.now || c.tz)) { const x = сейчасВГороде(c.now, c.tz, c.город); if (x) c.сейчас = x; }
    return c;
  }

  /* Переключатели «Галочек»: что есть в карточке и можно менять. Дальний выезд — только КП (в МНЧ и БТ поля нет) */
  const ГАЛОЧКИ = [['urgent', 'Срочная', 'is_urgent'], ['callCheck', 'Прозвон', 'is_need_call_check'], ['callBeforeVisit', 'Перед выездом', 'is_need_call_before_visit'],
    ['zakrep', 'Закреп', 'is_zakrep'], ['fback', 'Отзыв', 'is_req_fback'], ['farRide', 'Дальний выезд', 'is_far_ride']];
  function переключатели(snap) {
    const s = снимок(snap), f = s.flags || {}, e = s.flagsEnabled || {};
    return ГАЛОЧКИ.map(([name, label, field]) => ({ name, label, field: 'CustomerRequest[' + field + ']', on: !!f[name],
      enabled: f[name] !== null && f[name] !== undefined && e[name] !== false && !(name === 'farRide' && s.dir !== 'kp') }))
      .filter((x) => x.enabled);
  }

  /* ======================== «ЧТО В ЗАЯВКЕ» (2.1) ========================
     Сводка карточки CRM для экрана, только чтение: сверху 2–3 строки (статус и визит; тип, город, вид работ и услуг; галочки и
     претензия), остальное — «подробнее» (комментарии, все «Переносы», адрес клиента, претензии). Телефоны — маской.
     подр — snap {details}: {comment, service, partner, changes[], address}; претензии — snap {claims}: {ok, count, list:[{id, status}]}
     o.безСтатуса — первую строку не показывать (в сетке статус и визит уже в шапке); o.претензииЖдём — список претензий ещё читается */
  const ПРЕТЕНЗИЯ_НЕТ = 'претензии по заявке в CRM нет';
  function претензииКратко(пр, o) {
    const x = o || {};
    if (x.претензииЖдём && !пр) return 'претензия: смотрю в CRM…';
    if (!пр || typeof пр !== 'object') return '';
    if (пр.ok === false) return 'претензия: список ОКК не прочитался';
    const list = Array.isArray(пр.list) ? пр.list : [];
    if (!list.length) return x.иНет ? ПРЕТЕНЗИЯ_НЕТ : '';
    return list.slice(0, 2).map((c) => 'претензия № ' + c.id + ' — «' + (c.status || 'статус не прочитан') + '»').join(', ') + (list.length > 2 ? ' и ещё ' + (list.length - 2) : '');
  }
  function чтоВЗаявке(snap, подр, претензии, o) {
    const s = снимок(snap), d = подр && typeof подр === 'object' ? подр : {}, x = o || {};
    const isoВ = isoДаты(s.visitDate);
    const визит = [isoВ ? дмг(isoВ) : '', чм(s.visitTime)].filter(Boolean).join(' ');
    const вид = [s.applName, s.subName].filter(Boolean).join(' → ');
    const галочки = ГАЛОЧКИ.filter(([k]) => s.flags[k] === true).map(([, t]) => t);
    const пр = претензииКратко(претензии, x);
    const сверху = [
      x.безСтатуса ? '' : ['«' + (s.statusName || СТАТУСЫ[s.statusCode] || '—') + '»', визит ? 'визит ' + визит : 'визит не указан'].join(' · '),
      [Н.причины.тип[s.type] || 'тип не указан', s.cityName || 'город не указан', вид ? 'вид работ: ' + вид : 'вид работ не указан'].join(' · '),
      [галочки.length ? '✓ ' + галочки.join(', ') : 'галочек нет', пр].filter(Boolean).join(' · '),
    ].filter(Boolean);
    const ещё = [];
    for (const [k, label] of [['comment', 'Комментарий'], ['service', 'Служебный комментарий'], ['partner', 'Комментарий партнёра']]) {
      const t = String(d[k] == null ? '' : d[k]).trim();
      if (t) ещё.push({ label, text: маскаТел(t) });
    }
    const переносы = (Array.isArray(d.changes) ? d.changes : []).map((t) => маскаТел(String(t).trim())).filter(Boolean);
    if (переносы.length) ещё.push({ label: 'Переносы (' + переносы.length + ')', lines: переносы });
    if (String(d.address || '').trim()) ещё.push({ label: 'Адрес клиента', text: маскаТел(String(d.address).trim()) });
    const список = претензии && претензии.ok !== false && Array.isArray(претензии.list) ? претензии.list : [];
    if (список.length) ещё.push({ label: 'Претензии (' + список.length + ')', lines: список.map((c) => '№ ' + c.id + ' — «' + (c.status || 'статус не прочитан') + '»' + (c.type ? ', ' + c.type : '') + (c.created ? ', от ' + c.created : '')) });
    return { сверху, ещё };
  }

  /* ======================== ДОСТУПНОСТЬ ======================== */
  // почему действие недоступно: '' — доступно
  function почемуНет(key, s, c) {
    const d = КАТАЛОГ[key];
    if (!d) return 'нет такого действия';
    if (d.off) return 'ещё не включено';
    const st = s.statusCode || кодСтатуса(s.statusName);
    if (!d.матрица[st]) return 'не для статуса «' + (СТАТУСЫ[st] || s.statusName || '?') + '»';
    if (!кнопкаЕсть(s, d.needButton)) return 'в карточке CRM нет кнопки «' + d.label + '»';
    // правила действия другого пакета: доступно(snap, ctx) (PE) или правило(snap, ctx) → '' или почему нет
    for (const r of [d.доступно, d.правило]) if (typeof r === 'function') { const x = r(s, c); if (x) return String(x); }
    const чужая = s.held && s.held.yes && !s.held.mine;
    switch (key) {
      case 'cancel_branch': if (Number(s.type) === 30) return 'тип «Гарантия» — только «Отмена КЦ»'; break;
      case 'take': if (чужая) return 'заявку держит другой сотрудник'; if (s.held && s.held.mine) return 'уже взята вами'; break;
      case 'release': if (!(s.held && s.held.mine)) return чужая ? 'заявку держит другой сотрудник' : 'заявка не взята'; break;
      case 'pz_take': case 'pz_agreed': case 'pz_noanswer': case 'pz_release':
        if (!(s.flags && s.flags.callCheck)) return 'нет «Прозвона»';
        if (чужая) return 'заявку прозванивает другой';
        if (key === 'pz_take' ? s.held && s.held.yes : !(s.held && s.held.mine)) return key === 'pz_take' ? 'уже взята вами' : 'сначала «Взять прозвон»';
        if (key === 'pz_noanswer' && !кнопкаЕсть(s, 'noAnswer')) return 'в карточке CRM нет кнопки «Не отвечает»';
        break;
      case 'flags': if (!переключатели(s).length) return 'галочки в карточке недоступны'; break;
      case 'claim': if (c.hasClaim) return 'претензия уже есть — «Снова звонит»'; break;
      // неизвестно (претензию могли создать в CRM, сообщения в чате нет) — плитка есть: карточка спросит CRM (сведения), «нет» — откажет
      case 'claim_again': if (c.hasClaim === false) return 'претензии ещё нет'; break;
      case 'claim_reply': if (c.hasClaim !== true) return 'претензия в CRM не подтверждена'; break;
      case 'transfer': if (!(s.transferServers || []).length) return 'в городе нет другого направления'; break;
      case 'sama':
        if (!Н.решения.самаНабрала.includes(s.dir)) return 'в ' + (Н.базы.имя[s.dir] || s.dir) + ' «сама набрала» не пишут (регламент: чат «БТ/МНЧ Модерации»)';
        // регламент: «Взять в работу» → «сама набрала». Держит другой — он и звонит клиенту; наше «сама набрала» его перебьёт
        if (чужая) return 'заявку держит другой сотрудник';
        if (c.чаты && !(TG() && TG().moderationChat(c.чаты, s.dir))) return 'нет чата «Модерации» ' + (Н.базы.имя[s.dir] || '');
        break;
      case 'addr': case 'phone_add': case 'name': if (!Н.решения.карточкаКлиента.includes(st)) return 'карточку клиента меняем только в «Ожидает», «В пути», «На уточнении», «Модерации»'; break;
      case 'city': case 'worktype':
        if ((key === 'city' ? s.cityEditable : s.applEditable) === false) return 'поле «' + (key === 'city' ? 'Город' : 'Вид работ') + '» в карточке CRM недоступно для изменения';
        if (чужая) return 'заявку держит другой сотрудник';
        break;
      default:
    }
    return '';
  }
  const плиткаИз = (x, s, c) => {
    const t = typeof x === 'string' ? { key: x, id: x } : { ...x };
    const d = КАТАЛОГ[t.key] || {};
    return { key: t.key, id: t.id || t.key, label: t.label || (ПОДПИСИ[t.key] ? ПОДПИСИ[t.key](s, c) : d.label), icon: d.icon || 'check', group: d.group || '', ...(t.ввод ? { ввод: t.ввод } : {}) };
  };
  /* Плитки по снимку: основные (5.2, до 6) + остальные доступные («Ещё»); в каждой — key, id, label, icon, primary, group, hint, ввод */
  function доступные(snap, ctx) {
    const s = снимок(snap), c = контекст(ctx);
    const ok = (key) => !почемуНет(key, s, c);
    const out = [], ids = new Set();
    let основные = основныеДля(s, c);
    // время визита прошло больше 10 мин (1/4) — «Где мастер?» первой (4.3)
    if ([1, 4].includes(s.statusCode) && Number(c.опоздание) > Н.пороги.опозданиеОтменаМин) основные = ['where', ...основные.filter((x) => x !== 'where')];
    // чип одной галочки («Срочная», «Прозвон»): поля нет или оно disabled — плитки нет (иначе карточка без «Сделать»)
    const галочкаНельзя = (t) => t.key === 'flags' && t.ввод && Object.keys(t.ввод).some((n) => !переключатели(s).some((x) => x.name === n));
    for (const x of основные) {
      const t = плиткаИз(x, s, c);
      if (ids.has(t.id) || !ok(t.key) || галочкаНельзя(t) || out.length >= 6) continue;
      ids.add(t.id); out.push({ ...t, primary: true });
    }
    for (const key of Object.keys(КАТАЛОГ)) {
      if (!ok(key) || out.some((t) => t.key === key && t.id === key)) continue;
      // «Галочки» и «НФ с причиной» в «Ещё» — общей плиткой, даже если их частные плитки в основных
      if (out.some((t) => t.key === key) && !['flags', 'precheck_close'].includes(key)) continue;
      ids.add(key); out.push({ ...плиткаИз(key, s, c), primary: false });
    }
    for (const t of out) { const h = подсказкаПлитки(t, s, c); if (h) t.hint = h; }
    return out;
  }
  function подсказкаПлитки(t, s, c) {
    if (t.key === 'cancel_kc') return КАТАЛОГ.cancel_kc.money;
    if (t.key === 'to_not_taken' && s.partnerAskNoCall && ЖИВЫЕ.includes(s.statusCode)) return 'партнёр просил «без прозвона»';
    if (t.key === 'where' && Number(c.опоздание) > Н.пороги.опозданиеОтменаМин) return 'опаздывает ' + c.опоздание + ' мин';
    if (t.key === 'sama') return 'клиент перезвонил сам';
    return '';
  }
  /* «Нет здесь: …» — недоступные действия с причиной (по запросу оператора) */
  function недоступные(snap, ctx) {
    const s = снимок(snap), c = контекст(ctx);
    return Object.keys(КАТАЛОГ).filter((k) => !КАТАЛОГ[k].off).map((key) => ({ key, label: КАТАЛОГ[key].label, почему: почемуНет(key, s, c) })).filter((x) => x.почему);
  }

