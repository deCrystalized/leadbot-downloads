  function доделать(p) {
    if (p.tg && !p.tg.kind) p.tg = { ...p.tg, kind: null, on: false };
    if (p.tg) {
      p.tg.on = !!(p.tg.on && p.tg.text && p.tg.kind);
      // одна строка «Переносов» — экран сам подставит строку CRM после записи (как «Скопировать перенос» Чатерского);
      // несколько строк — LC_ACT.текстПослеCRM(план, итоги шагов)
      if (p.tg.послеCRM && p.tg.послеCRM.строка && !p.tg.послеCRM.префикс) { p.tg.изCRM = true; p.tg.suffix = p.tg.послеCRM.суффикс || ''; }
    }
    if (p.client) p.client.on = !!(p.client.on && p.client.text);
    for (const x of p.steps) if (!x.title) x.title = x.name || x.action || '';
    if (!Array.isArray(p.crm)) p.crm = p.already && !p.steps.length ? ['в CRM уже так — не меняем'] : p.steps.map((x) => x.title);
    p.missing = [...new Set(p.missing || [])];
    if (p.missing.length) p.ok = false;
    if (!p.ok && !p.why) p.why = p.недоступно || (p.missing.length ? 'не заполнено: ' + p.missing.join(', ') : '');
    p.warnings = [...new Set(p.warnings || [])];
    return p;
  }
