  function подсказка(источник, snap, данные) {
    const s = снимок(snap), c = контекст(данные);
    let r = null;
    if (источник === 'ai') r = изПереписки(s, c);
    else if (источник === 'jivo_claim_rule' && c.rule_action === true && c.намерение === 'jivo_claim_reply') r = изПереписки(s, c);
    else if (источник === 'rules') r = поПравилам(s, c).find((x) => !x.key || !КАТАЛОГ[x.key] || !почемуНет(x.key, s, c)) || null;
    else if (источник === 'watch') r = поСобытию(s, c);
    else {
      // свои источники других пакетов (PE: «leadchat-addr» — новый адрес, распознанный в LeadChat): спрашиваем их действия
      for (const d of Object.values(КАТАЛОГ)) {
        if (d.off || typeof d.подсказка !== 'function') continue;
        try { r = d.подсказка(источник, s, c) || null; } catch (_e) { r = null; }
        if (r) break;
      }
    }
    // запасные варианты — тоже только доступные (нет кнопки «Отмена КЦ» — не предлагаем её вторым)
    if (r && Array.isArray(r.ещё)) { r.ещё = r.ещё.filter((x) => x && (!КАТАЛОГ[x.key] || !почемуНет(x.key, s, c))); if (!r.ещё.length) delete r.ещё; }
    // подсказываем только то, что можно сделать: действие включено, доступно по статусу и кнопкам (кроме «отдел_авито» — это LeadChat)
    if (r && r.key && КАТАЛОГ[r.key] && почемуНет(r.key, s, c)) {
      // напоминание по сроку регламента (недозвон, уточнение) не теряем: кнопки нет — тихо «сделайте в CRM», без действия
      if (источник !== 'watch') return null;
      return { key: null, ввод: {}, почему: r.почему + ' — сделайте в CRM (здесь недоступно: ' + почемуНет(r.key, s, c) + ')', тихо: true, ...(r.через !== undefined ? { через: r.через } : {}), ...(r.в !== undefined ? { в: r.в } : {}) };
    }
    return r;
  }
