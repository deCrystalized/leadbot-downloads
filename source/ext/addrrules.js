  function ключДома(h) { return точныйКлючДома(String(h || '').replace(/\s*\/\s*(?=\d)/g, 'к')); }
  const имяКак = (s) => String(s || '').trim().replace(/\s+/g, ' ').replace(/[.,;:!?]+$/, '')
    .split(' ').map((w) => (/^\d/.test(w) || w.length <= 2 ? w : w[0].toUpperCase() + w.slice(1))).join(' ');
