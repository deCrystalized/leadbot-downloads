/* РАБОТА БЕЗ ИИ (лимит месяца исчерпан или ИИ выключен вручную): то, что умеют правила модулей расширения.
   Ничего не выдумываем: чего правила не знают — пусто, и проверка это покажет («нет сути», «проверьте согласование»). */
'use strict';

const БЕЗ_ИИ = 'ИИ выключен до 1-го числа (лимит) — разобрано правилами, проверьте';
// экономный режим (80–100% лимита): «Готовые» / мгновенная проверка «Входящих» — без ИИ; панель оператора — с ИИ
const ЭКОНОМ_ОЧЕРЕДЬ = 'экономный режим: «Готовые» без ИИ — разобрано правилами; откройте диалог — разберёт ИИ';

function создатьПравила(M) {
  const { LC_EXTRACT, LC_ADDR_RULES, LC_CHECK } = M;

  /* разбор переписки: телефон, время, голосовые — правила validate; адрес — правила адреса (addrrules) */
  function extract(ctx, почему) {
    const msgs = (ctx.messages || []).filter(LC_EXTRACT.речь);
    const rr = LC_ADDR_RULES.parse(msgs, ctx.city);
    const ai = rr ? { street: rr.street, building: rr.house, settlement: rr.settlement, office: rr.flat, entrance: rr.entrance, floor: rr.floor, intercom: !!rr.intercom } : {};
    const r = LC_EXTRACT.validate(ai, ctx);
    const checks = [...r.checks, { field: 'ai', ok: false, note: почему || БЕЗ_ИИ }];
    return { ok: true, lead: r.lead, checks, rules: true };
  }

  /* регламент: пункты раздела есть, а сверить их с перепиской некому — все «не уточнено»;
     согласование — только то, что видно по словам клиента, иначе «проверьте» по правилам раздела */
  function checklist(c, клиент) {
    const итог = LC_CHECK.итогСогласования('', c.rules, c.free, клиент);
    const maybe = итог.maybe || (c.rules.length ? c.rules[0] : '');
    return { ok: true, section: c.section, results: c.items.map((item) => ({ item, done: false, answer: '' })), approval: '',
      maybe, maybeWhy: итог.maybe ? итог.why : (c.rules.length ? 'ИИ выключен — сверьте правила согласования раздела сами' : ''), rules: c.rules, refuse: '', aiOff: true };
  }

  /* что дописал клиент: явные отмена / перенос / «где мастер?» / претензия; вежливое без сути («спасибо, ждём мастера
     завтра», «ок, договорились») — не важно: дело из вежливости не выдумываем. Остальное со смыслом («домофон не работает,
     позвоните») — дополнение словами клиента (карточка, отправка — только по кнопке) */
  const ПРОСТО = /^(ок|окей|ok|хорошо|спасибо|спс|понял|поняла|ясно|ага|да|жду|ждём|ждем|договорились|👍|\+)[\s.!)]*$/i;
  const ОТМЕНА = /отмен|не\s+нужн|не\s+актуальн|передумал|сам[аи]?\s+(починил|сделал)|не\s+надо/i;
  const ПЕРЕНОС = /перенес|перенест|друг(ой|ое|ую)\s+(день|время|дату)|не\s+(смогу|успею|получится)|попозже|позже|пораньше/i;
  // «где мастер» — явный вопрос или жалоба на опоздание; «когда приедет / мастер едет» — только с вопросительным знаком
  const ГДЕ = /где\s+(же\s+)?(ваш\s+|наш\s+)?мастер|мастер\s+(так\s+и\s+|до\s+сих\s+пор\s+|вс[её]\s+ещ[её]\s+|ещ[её]\s+)?не\s+(приехал|пришёл|пришел)|никто\s+не\s+(приехал|пришёл|пришел)|опаздыва|опоздал/i;
  const ГДЕ_ВОПРОС = /(когда|скоро\s+ли|скоро)\s+(мастер\s+)?(приедет|будет|придёт|придет)|мастер\s+(едет|выехал|будет|приедет)|мастер[^.!?]{0,25}\s(приедет|будет|придёт|придет)|ждать\s+мастера/i;
  const ВЕЖЛИВО = new Set(('ок окей ok хорошо спасибо спасибочки спс благодарю большое огромное понял поняла поняли ясно ага да угу жду ждём ждем '
    + 'будем буду ждать ожидаю ожидаем мастера мастер его вас едет выехал приедет придёт придет будет приехал пришёл пришел сделал сделали дома тогда завтра сегодня послезавтра утром днём днем вечером договорились отлично '
    + 'супер прекрасно замечательно хорошего дня всего доброго до свидания здравствуйте добрый привет и вам тоже всё все так понятно принято').split(' '));
  const безСути = (t) => t.toLowerCase().replace(/[^a-zа-яё0-9\s]/gi, ' ').split(/\s+/).filter(Boolean).every((w) => ВЕЖЛИВО.has(w));
  const ПРЕТЕНЗИЯ = /жалоб|претенз|плохо\s+сделал|опять\s+(не\s+работает|сломал|течёт|течет)|снова\s+(не\s+работает|сломал|течёт|течет)|вернуть\s+деньги|обманул/i;
  function addition(fresh) {
    const текст = (fresh || []).filter((m) => m && m.direction === 'in').map((m) => String((m.body || '') + ' ' + (m.voice_transcript || '')).trim()).filter(Boolean).join(' / ');
    const t = текст.replace(/\s+/g, ' ').trim();
    if (!t || ПРОСТО.test(t)) return { intent: 'нет', important: false, summary: '', date: '', time: '', reason: '', rules: true };
    const где = ГДЕ.test(t) || (ГДЕ_ВОПРОС.test(t) && /\?/.test(t));
    const intent = ОТМЕНА.test(t) ? 'отмена' : ПЕРЕНОС.test(t) ? 'перенос' : где ? 'где_мастер' : ПРЕТЕНЗИЯ.test(t) ? 'претензия'
      : t.length >= 12 && !безСути(t) ? 'дополнение' : 'нет';
    const кратко = t.slice(0, 200);
    return { intent, important: intent !== 'нет', summary: intent === 'нет' ? '' : кратко, date: '', time: '', reason: intent === 'отмена' ? кратко.slice(0, 120) : '', rules: true };
  }

  return { extract, checklist, addition, БЕЗ_ИИ };
}

module.exports = { создатьПравила, БЕЗ_ИИ, ЭКОНОМ_ОЧЕРЕДЬ };
